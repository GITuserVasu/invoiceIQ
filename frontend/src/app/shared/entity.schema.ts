/** Response from GET /api/v1/tenants/:id/entities/:entityId/dashboard */
export interface EntityDashboardResponse {
  entity: EntityDbRow;
  settings: EntitySettingsDbRow;
  intakeChannels: IntakeChannelDbRow[];
  matchingPolicy: MatchingPolicyDbRow | null;
  modules: ModuleDbRow[];
  roles: EntityRoleDbRow[];
  assignments: Record<string, unknown>[];
  classifications: Record<string, unknown>[];
}

