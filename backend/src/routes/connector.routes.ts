async function auditSync(pool: Pool, tenantId: string, entityUuid: string, req: any, action: string, channel: string, result: any): Promise<void> {
  try {
    const ekRow = await pool.query(`SELECT entity_key FROM entities WHERE id=$1`, [entityUuid]);
    const actorEmail = (req.headers?.['x-actor-email'] as string) || '';
    const actorName  = (req.headers?.['x-actor-name']  as string) || '';
    await pool.query(
      `INSERT INTO audit_events (tenant_id, actor_user_id, action, resource_type, resource_id, metadata)
       VALUES ($1, NULL, $2, 'intake_channel', $3, $4::jsonb)`,
      [tenantId, action, entityUuid, JSON.stringify({
        entityId: ekRow.rows[0]?.entity_key, module: 'Data Connectors', target: channel,
        severity: 'low', result: 'success', after: JSON.stringify(result ?? {}),
        actorEmail, actorName, traceId: 'TRC-' + entityUuid.slice(0,8).toUpperCase()
      })]
    );
  } catch { /* never break main flow */ }
}

